import { maxWireValue } from './schema';
import type { FieldSchema } from './schema';
import type { CompiledMessage } from './compiler';

const BANNER = `// AUTO-GENERATED by ghostc (@ghost-acoustics/schema-compiler). DO NOT EDIT.
// Regenerate with: pnpm --filter @ghost-acoustics/schema-compiler compile
`;

/** VENUE_CUE -> VenueCue */
export function pascalCase(screamingSnake: string): string {
  return screamingSnake
    .split('_')
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

const hex = (op: number): string => `0x${op.toString(16).toUpperCase().padStart(2, '0')}`;
const lit = (n: number): string => JSON.stringify(n);
const jsDoc = (text: string | undefined, indent = '  '): string => (text ? `${indent}/** ${text.replace(/\*\//g, '* /')} */\n` : '');

function tsType(field: FieldSchema): string {
  return field.type === 'boolean' ? 'boolean' : field.type === 'bytes' ? 'Uint8Array' : 'number';
}

// ---- types.ts -------------------------------------------------------------

export function emitTypes(messages: readonly CompiledMessage[]): string {
  const blocks = messages.map(({ schema, report }) => {
    const fields = schema.fields
      .map((f) => {
        const detail =
          f.type === 'quantizedInt'
            ? `quantizedInt [${f.min}, ${f.max}] in ${f.bits} bits`
            : f.type === 'bytes'
              ? `bytes, 0..${f.maxLength}, length implied by the frame`
              : f.type;
        return `${jsDoc(f.description ? `${f.description} (${detail})` : detail)}  ${f.name}: ${tsType(f)};`;
      })
      .join('\n');
    const doc = `/**\n * ${schema.name} (opcode ${hex(schema.opcode)}): ${report.payloadBytes} B payload, ` +
      `${report.frameBytes} B frame, ~${report.airtimeSeconds.toFixed(3)} s airtime.` +
      `${schema.description ? `\n * ${schema.description}` : ''}\n */`;
    return `${doc}\nexport interface ${pascalCase(schema.name)} {\n${fields}${fields ? '\n' : ''}}`;
  });

  const map = messages.map(({ schema }) => `  ${schema.name}: ${pascalCase(schema.name)};`).join('\n');
  return `${BANNER}
${blocks.join('\n\n')}

/** Message name -> payload type. */
export interface MessageTypeMap {
${map}
}

export type MessageName = keyof MessageTypeMap;
`;
}

// ---- opcodes.ts -----------------------------------------------------------

export function emitOpcodes(messages: readonly CompiledMessage[]): string {
  const entries = messages.map(({ schema }) => `  ${schema.name}: ${hex(schema.opcode)},`).join('\n');
  const registry = messages
    .map(
      ({ schema, report }) =>
        `  { name: '${schema.name}', opcode: ${hex(schema.opcode)}, hex: '${hex(schema.opcode)}', ` +
        `payloadBytes: ${report.payloadBytes}, frameBytes: ${report.frameBytes}, airtimeSeconds: ${lit(report.airtimeSeconds)} },`,
    )
    .join('\n');
  return `${BANNER}
/** Application opcode registry (0x00-0x0F is reserved for the core protocol). */
export const Opcode = {
${entries}
} as const;

export type OpcodeName = keyof typeof Opcode;
export type OpcodeValue = (typeof Opcode)[OpcodeName];

export interface OpcodeInfo {
  readonly name: OpcodeName;
  readonly opcode: OpcodeValue;
  readonly hex: string;
  readonly payloadBytes: number;
  readonly frameBytes: number;
  /** Estimated airtime in seconds at the baseline bitrate. */
  readonly airtimeSeconds: number;
}

export const OPCODE_REGISTRY: readonly OpcodeInfo[] = [
${registry}
];

/** Reverse lookup; undefined for unregistered opcodes. */
export function opcodeName(opcode: number): OpcodeName | undefined {
  return OPCODE_REGISTRY.find((info) => info.opcode === opcode)?.name;
}
`;
}

// ---- serializers.ts -------------------------------------------------------

const HELPER_BITS = `/** Writes the low \`width\` bits (<= 32) of \`value\`, MSB first, into a zeroed region. */
function writeBits(buf: Uint8Array, bitPos: number, value: number, width: number): void {
  let remaining = width;
  let pos = bitPos;
  while (remaining > 0) {
    const space = 8 - (pos & 7);
    const take = remaining < space ? remaining : space;
    const chunk = Math.floor(value / 2 ** (remaining - take)) & ((1 << take) - 1);
    buf[pos >>> 3]! |= chunk << (space - take);
    pos += take;
    remaining -= take;
  }
}

/** Reads \`width\` bits (<= 32) as an unsigned integer, MSB first. */
function readBits(buf: Uint8Array, bitPos: number, width: number): number {
  let remaining = width;
  let pos = bitPos;
  let result = 0;
  while (remaining > 0) {
    const space = 8 - (pos & 7);
    const take = remaining < space ? remaining : space;
    result = result * (1 << take) + ((buf[pos >>> 3]! >>> (space - take)) & ((1 << take) - 1));
    pos += take;
    remaining -= take;
  }
  return result;
}
`;

const HELPER_UINT = `function assertUint(value: number, max: number, label: string): number {
  if (!(Number.isInteger(value) && value >= 0 && value <= max)) {
    throw new RangeError(\`\${label}: \${value} is not an integer in [0, \${max}]\`);
  }
  return value;
}
`;

const HELPER_QUANT = `function quantize(value: number, min: number, max: number, levels: number, label: string): number {
  if (!(value >= min && value <= max)) throw new RangeError(\`\${label}: \${value} outside [\${min}, \${max}]\`);
  return Math.round(((value - min) * levels) / (max - min));
}

function dequantize(wire: number, min: number, max: number, levels: number): number {
  return min + (wire * (max - min)) / levels;
}
`;

const textBytesConst = (m: CompiledMessage): string => `${m.schema.name}_${m.layout.variable!.name.toUpperCase()}_MAX_BYTES`;
const fixedBytesConst = (m: CompiledMessage): string => `${m.schema.name}_FIXED_BYTES`;

function emitPack(m: CompiledMessage): string {
  const { schema, layout } = m;
  const type = pascalCase(schema.name);
  const lines = layout.slots
    .filter(({ field }) => field.type !== 'bytes')
    .map(({ field, bitOffset, bitWidth }) => {
      const label = `'${schema.name}.${field.name}'`;
      const src = `msg.${field.name}`;
      const at = `base + ${bitOffset}`;
      switch (field.type) {
        case 'boolean':
          return `  writeBits(out, ${at}, ${src} ? 1 : 0, 1);`;
        case 'quantizedInt':
          return `  writeBits(out, ${at}, quantize(${src}, ${lit(field.min)}, ${lit(field.max)}, ${maxWireValue(field.bits)}, ${label}), ${bitWidth});`;
        default:
          return `  writeBits(out, ${at}, assertUint(${src}, ${maxWireValue(bitWidth)}, ${label}), ${bitWidth});`;
      }
    });
  const hasFixed = lines.length > 0;
  const body = `${hasFixed ? '  const base = offset * 8;\n' : ''}${lines.join('\n')}${hasFixed ? '\n' : ''}`;

  if (layout.variable) {
    const v = layout.variable;
    const max = textBytesConst(m);
    const fixed = fixedBytesConst(m);
    return `/**
 * Packs ${schema.name} into \`out\` at byte \`offset\`. Returns bytes written (${layout.fixedBytes} + the length of \`${v.name}\`, at most ${layout.payloadBytes}).
 * The length of \`${v.name}\` is not sent: the receiver infers it from the frame's payload length.
 */
export function pack${type}(msg: ${type}, out: Uint8Array, offset = 0): number {
  const length = msg.${v.name}.length;
  if (length > ${max}) {
    throw new RangeError(\`${schema.name}.${v.name}: \${length} bytes exceeds the maximum of \${${max}}\`);
  }
  const size = ${fixed} + length;
  if (out.length - offset < size) {
    throw new RangeError(\`${schema.name}: output buffer too small (need \${size} bytes)\`);
  }
  out.fill(0, offset, offset + size);
${body}  out.set(msg.${v.name}, offset + ${fixed});
  return size;
}`;
  }

  return `/** Packs ${schema.name} into \`out\` at byte \`offset\`. Returns bytes written (${layout.payloadBytes}). Allocation-free. */
export function pack${type}(${hasFixed ? 'msg' : '_msg'}: ${type}, out: Uint8Array, offset = 0): number {
  if (out.length - offset < ${schema.name}_PAYLOAD_BYTES) {
    throw new RangeError('${schema.name}: output buffer too small (need ${layout.payloadBytes} bytes)');
  }
  out.fill(0, offset, offset + ${schema.name}_PAYLOAD_BYTES);
${body}  return ${schema.name}_PAYLOAD_BYTES;
}`;
}

function emitUnpack(m: CompiledMessage): string {
  const { schema, layout } = m;
  const type = pascalCase(schema.name);
  const lines = layout.slots
    .filter(({ field }) => field.type !== 'bytes')
    .map(({ field, bitOffset, bitWidth }) => {
      const read = `readBits(buf, base + ${bitOffset}, ${bitWidth})`;
      switch (field.type) {
        case 'boolean':
          return `  out.${field.name} = ${read} === 1;`;
        case 'quantizedInt':
          return `  out.${field.name} = dequantize(${read}, ${lit(field.min)}, ${lit(field.max)}, ${maxWireValue(field.bits)});`;
        default:
          return `  out.${field.name} = ${read};`;
      }
    });
  const hasFixed = lines.length > 0;
  const body = `${hasFixed ? '  const base = offset * 8;\n' : ''}${lines.join('\n')}${hasFixed ? '\n' : ''}`;

  if (layout.variable) {
    const v = layout.variable;
    const fixed = fixedBytesConst(m);
    return `/**
 * Unpacks ${schema.name} from \`buf[offset, end)\` into the caller-supplied \`out\`.
 * \`out.${v.name}\` becomes a view into \`buf\` (no copy): copy it if \`buf\` will be reused.
 */
export function unpack${type}(buf: Uint8Array, out: ${type}, offset = 0, end: number = buf.length): ${type} {
  const size = end - offset;
  if (size < ${fixed} || size > ${schema.name}_PAYLOAD_BYTES) {
    throw new RangeError(\`${schema.name}: payload of \${size} bytes does not fit (expected ${layout.fixedBytes}..${layout.payloadBytes})\`);
  }
${body}  out.${v.name} = buf.subarray(offset + ${fixed}, end);
  return out;
}`;
  }

  return `/** Unpacks ${schema.name} from \`buf\` at byte \`offset\` into the caller-supplied \`out\`. Allocation-free. */
export function unpack${type}(buf: Uint8Array, out: ${type}, offset = 0): ${type} {
  if (buf.length - offset < ${schema.name}_PAYLOAD_BYTES) {
    throw new RangeError('${schema.name}: input buffer too small (need ${layout.payloadBytes} bytes)');
  }
${body}  return out;
}`;
}

export function emitSerializers(messages: readonly CompiledMessage[]): string {
  const fields = messages.flatMap((m) => m.schema.fields);
  const usesBits = fields.some((f) => f.type !== 'bytes');
  const usesUint = fields.some((f) => f.type === 'uint8' || f.type === 'uint16' || f.type === 'uint32');
  const usesQuant = fields.some((f) => f.type === 'quantizedInt');

  const imports = `import type { ${messages.map((m) => pascalCase(m.schema.name)).join(', ')} } from './types';`;
  const helpers = [usesBits ? HELPER_BITS : '', usesUint ? HELPER_UINT : '', usesQuant ? HELPER_QUANT : '']
    .filter(Boolean)
    .join('\n');

  const consts = messages
    .map((m) => {
      const { schema, layout } = m;
      const lines = [
        `/** ${layout.variable ? 'Maximum' : 'Exact'} payload size of ${schema.name} in bytes (${layout.payloadBits} bits, MSB-first, zero-padded). */`,
        `export const ${schema.name}_PAYLOAD_BYTES = ${layout.payloadBytes};`,
      ];
      if (layout.variable) {
        lines.push(
          `/** Bytes before the variable-length \`${layout.variable.name}\` field. */`,
          `export const ${fixedBytesConst(m)} = ${layout.fixedBytes};`,
          `/** Maximum length of \`${layout.variable.name}\` in bytes. */`,
          `export const ${textBytesConst(m)} = ${layout.variable.maxLength};`,
        );
      }
      return lines.join('\n');
    })
    .join('\n');

  const fns = messages.map((m) => `${emitPack(m)}\n\n${emitUnpack(m)}`).join('\n\n');

  const registry = messages
    .map(({ schema }) => {
      const t = pascalCase(schema.name);
      return `  ${schema.name}: { opcode: ${hex(schema.opcode)}, payloadBytes: ${schema.name}_PAYLOAD_BYTES, pack: pack${t}, unpack: unpack${t} },`;
    })
    .join('\n');

  return `${BANNER}
${imports}

${helpers}
${consts}

${fns}

/** Lookup table for generic dispatch by message name. */
export const SERIALIZERS = {
${registry}
} as const;
`;
}
